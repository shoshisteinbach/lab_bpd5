def _rtl_run(run, bold=False, size=11, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)
    rpr = run._element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.append(fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs"):
        fonts.set(qn(attr), FONT)
    rtl = OxmlElement("w:rtl")
    rpr.append(rtl)
    if bold:
        rpr.append(OxmlElement("w:bCs"))
    szcs = OxmlElement("w:szCs")
    szcs.set(qn("w:val"), str(size * 2))
    rpr.append(szcs)


def _rtl_par(par):
    ppr = par._element.get_or_add_pPr()
    ppr.append(OxmlElement("w:bidi"))
    par.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def add_text(doc_or_cell, text, bold=False, size=11, color=None, style=None):
    """פסקה. אפשר לסמן חלקים מודגשים עם **כוכביות**."""
    par = doc_or_cell.add_paragraph(style=style)
    _rtl_par(par)
    parts = text.split("**")
    for i, part in enumerate(parts):
        if part:
            _rtl_run(par.add_run(part), bold=bold or (i % 2 == 1), size=size, color=color)
    par.paragraph_format.space_after = Pt(6)
    return par


def heading(doc, text, level):
    sizes = {0: 20, 1: 16, 2: 13}
    par = doc.add_heading(level=level)
    _rtl_par(par)
    _rtl_run(par.add_run(text), bold=True, size=sizes[level], color="1F3864")
    return par


def bullets(doc, items):
    for item in items:
        add_text(doc, item, style="List Bullet")


def numbered(doc, items):
    for item in items:
        add_text(doc, item, style="List Number")


def table(doc, header, rows, widths_cm=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.autofit = False
    t._tbl.tblPr.append(OxmlElement("w:bidiVisual"))   # טבלה מימין לשמאל
    for i, h in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.paragraphs[0]._element.getparent().remove(cell.paragraphs[0]._element)
        add_text(cell, h, bold=True, size=10)
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:fill"), "D9E2F3")
        cell._tc.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].paragraphs[0]._element.getparent().remove(cells[i].paragraphs[0]._element)
            add_text(cells[i], str(val), size=10)
    if widths_cm:
        for row in t.rows:
            for i, w in enumerate(widths_cm):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return t


def csv_table(doc, path, header, decimals=1):
    """טבלה מתוך קובץ CSV שה-R שמר (כדי שהמספרים במסמך יהיו בדיוק מה שהקוד חישב)."""
    import csv
    with open(path, encoding="utf-8") as f:
        rows = list(csv.reader(f))[1:]
    def fmt(v):
        x = float(v)
        return str(int(x)) if x == int(x) else f"{x:.{decimals}f}"
    widths = [16.5 / len(header)] * len(header)
    return table(doc, header, [[fmt(v) for v in r] for r in rows], widths_cm=widths)


def image(doc, path, caption, width_cm=15):
    doc.add_picture(path, width=Cm(width_cm))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap = add_text(doc, caption, size=9, color="595959")
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER


